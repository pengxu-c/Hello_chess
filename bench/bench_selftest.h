// ============================================================================
// bench_selftest.h - 引擎正确性回归测试套件
//
// 设计目标：把「改坏了能不能立刻发现」变成可自动回答的问题。
// 每条用例都对应一个历史上真实出现过的失效模式：
//   T1 窗口索引       —— 旧稿 buildIndex() 清空 wins 后从未生成窗口，增量评估从未生效
//   T2 活四/冲四判定  —— bug2 第 1 条：outA/outB 两端对调，活四被降级、冲四被升级
//   T3 棋型梯度单调   —— 活三/眠三、活四/冲四 的量级必须严格拉开
//   T4 增量可逆       —— makeMove/unmakeMove 必须严格配对，否则搜索读到脏状态
//   T5 战术行为       —— 一步成五必须拿、对手一步成五必须堵（棋力下限的直接守护）
//   T6 多尺寸鲁棒性   —— 任意 n/w 组合都必须给出合法着法（n 子棋适配守护）
//
// 断言策略：优先使用**精确值断言**（T1/T2/T4），只有无法给出精确值时
// 才退化为**单调性断言**（T3/T5），避免把回归测试写成“看起来在测”。
// ============================================================================
#pragma once

#include <string>
#include <vector>

struct TestResult {
    std::string name;      // 用例名
    bool        passed;    // 是否通过
    std::string detail;    // 失败时的实际值 / 说明
};

// 运行全部用例。返回失败用例数量（0 表示全绿）。verbose 时逐条打印。
int runSelfTests(bool verbose, std::vector<TestResult>* out = nullptr);
